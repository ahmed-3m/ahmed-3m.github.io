/** The headline mean as a retrieval keyword (`99.03`), from the claims registry. */
const THESIS_MEAN_KEYWORD = claimParts('thesis.mean', 'en').number
const cifarBase = CIFAR_LAMBDA_SWEEP.find((entry) => entry.lambda === '0.0')!
const cifarOptimal = CIFAR_LAMBDA_SWEEP.find((entry) => entry.isOptimal)!
const cifarGain = formatClaim('thesis.gainPp', 'en', 'value')
const cifarHeadline = formatClaim('thesis.mean', 'en')
const seedList = (seeds: readonly number[]) => seeds.map((seed) => seed.toFixed(2)).join(', ')
const withinCifar = BENCHMARK_DATASETS.within_cifar
const inkjetBase = INKJET_OVERALL_SWEEP['0.0']

const benchmarkLines = (
  Object.values(BENCHMARK_DATASETS) as Array<(typeof BENCHMARK_DATASETS)[keyof typeof BENCHMARK_DATASETS]>
)
  .map(
    (ds) =>
      `${ds.key} (${ds.category}, nId=${ds.nId}, nOod=${ds.nOod}): AUROC ${ds.auroc.toFixed(2)}%, FPR95 ${ds.fpr95.toFixed(1)}%, AUPRC ${ds.auprc.toFixed(2)}%`
  )
  .join('; ')

const lambdaSweepLines = CIFAR_LAMBDA_SWEEP.map((entry) => {
  const meanPart =
    entry.withinCifarStd !== null
      ? `${entry.withinCifarMean.toFixed(2)}% ± ${entry.withinCifarStd.toFixed(2)}%`
      : `${entry.withinCifarMean.toFixed(2)}%`
  const artefact = entry.svhnArtefact ? ' (svhn artefact)' : ''
  return `lambda=${entry.lambda}: within-CIFAR ${meanPart}, SVHN ${entry.svhnAuroc.toFixed(2)}%${artefact}`
}).join('; ')

const kAblationLines = K_ABLATION_TABLE.map(
  (row) =>
    `K=${row.k}: AUROC ${row.auroc.toFixed(2)}%, FPR95 ${row.fpr95.toFixed(1)}%, ${row.msPerSample.toFixed(1)} ms/sample (${row.resnetMultiple})`
).join('; ')

const inkjetSweepLines = (
  Object.values(INKJET_OVERALL_SWEEP) as Array<
    (typeof INKJET_OVERALL_SWEEP)[keyof typeof INKJET_OVERALL_SWEEP]
  >
)
  .map((row) => {
    const pText = row.holmPValue !== null ? `, Holm p=${row.holmPValue.toFixed(3)}` : ' (baseline)'
    return `lambda=${row.lambda}: AUROC ${row.aurocMean.toFixed(4)} ± ${row.aurocStd.toFixed(4)}, acc ${row.accMean.toFixed(4)} ± ${row.accStd.toFixed(4)}, FPR95 ${row.fpr95Mean.toFixed(4)}${pText}`
  })
  .join('; ')

const inkjetFeatureLines = INKJET_PER_FEATURE.map((row) => {
  const base = row.byLambda['0.0']
  return `${row.feature} (ratio ${row.goodBadRatio}): ${base.mean.toFixed(4)} ± ${base.std.toFixed(4)}`
}).join('; ')

function blogFact(slug: string): string {
  const post = blogPostsMeta.find((entry) => entry.slug === slug)
  if (!post) return ''
  return `${post.translations.en.title} (${post.date}): ${post.translations.en.excerpt}`
}

