// Writes worker/prompt-bundle.js: the Worker's bundled copy of the published prompt file
// (spec 007, research R2). The Worker uses it when it cannot fetch
// https://ahmed-3m.github.io/genie/prompt.json. tests/genie/worker-prompt.test.ts fails
// when the committed copy differs from buildPromptFile().
// Run: npm run genie:worker-prompt

import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

import { buildPromptFile } from '../../src/lib/genie/prompt-file.ts'

export const BUNDLE_PATH = fileURLToPath(new URL('../../worker/prompt-bundle.js', import.meta.url))

export function renderWorkerPromptBundle(file = buildPromptFile()) {
  return [
    '// Generated by tools/genie/emit-worker-prompt.mjs from buildPromptFile(). Do not edit.',
    '// Regenerate with: npm run genie:worker-prompt',
    `export default ${JSON.stringify(file, null, 2)}`,
    '',
  ].join('\n')
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(BUNDLE_PATH, renderWorkerPromptBundle())
  console.log(`Wrote ${BUNDLE_PATH}`)
}
